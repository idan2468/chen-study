/**
 * One-off extraction of the seed content baked into the original standalone
 * HTML apps, so the 90+ Hebrew nikud card entries are transcribed mechanically
 * rather than by hand.
 *
 * Reads:  old/Modules Practice.html  (defaultModulesData, SAMPLE_MODULE_TEMPLATE)
 *         old/Unseen New.html        (defaultExercise)
 * Writes: src/data/*.ts
 *
 * Run from the repo root:  node scripts/extract-legacy-data.cjs
 */
const fs = require("node:fs")
const path = require("node:path")

const repoRoot = path.join(__dirname, "..")
const outDir = path.join(repoRoot, "src", "data")

const sliceLiteral = (src, marker, endMarker, closer) => {
  const start = src.indexOf(marker)
  if (start < 0) {
    throw new Error(`marker not found: ${marker}`)
  }
  const from = start + marker.length
  const end = src.indexOf(endMarker, from)
  if (end < 0) {
    throw new Error(`end marker not found for: ${marker}`)
  }
  return `${src.slice(from, end)}\n${closer}`
}

// The literals contain template strings (the `rule` HTML), so JSON.parse is not
// an option. They are pure data with no browser API access, so evaluating the
// expression in isolation is safe.
const evalLiteral = source => new Function(`return (${source})`)()

const banner = sourceFile => `/**
 * Seed content extracted verbatim from \`${sourceFile}\`.
 *
 * Generated by \`scripts/extract-legacy-data.cjs\` -- do not edit by hand.
 */`

const modulesHtml = fs.readFileSync(
  path.join(repoRoot, "old", "Modules Practice.html"),
  "utf8",
)
const unseenHtml = fs.readFileSync(
  path.join(repoRoot, "old", "Unseen New.html"),
  "utf8",
)

const modules = evalLiteral(
  sliceLiteral(modulesHtml, "const defaultModulesData = ", "\n        ];", "]"),
)
const sampleModule = evalLiteral(
  sliceLiteral(
    modulesHtml,
    "const SAMPLE_MODULE_TEMPLATE = ",
    "\n        };",
    "}",
  ),
)
const exercise = evalLiteral(
  sliceLiteral(unseenHtml, "const defaultExercise = ", "\n        };", "}"),
)

fs.writeFileSync(
  path.join(outDir, "defaultModules.ts"),
  `${banner("Modules Practice.html")}
import type { PracticeModule } from "../types/module"

/** The five built-in phonics modules. */
export const defaultModules: PracticeModule[] = ${JSON.stringify(modules, null, 2)}

/** Prefilled into the JSON loader's textarea as a starting point. */
export const sampleModule: PracticeModule = ${JSON.stringify(sampleModule, null, 2)}

/** Ids of the built-in modules, used to tell them apart from user-added ones. */
export const builtInModuleIds: readonly string[] = ${JSON.stringify(
    modules.map(m => m.id),
  )}
`,
)

fs.writeFileSync(
  path.join(outDir, "defaultExercise.ts"),
  `${banner("Unseen New.html")}
import type { Exercise } from "../types/exercise"

export const defaultExercise: Exercise = ${JSON.stringify(exercise, null, 2)}
`,
)

console.log(`modules: ${String(modules.length)}`)
for (const m of modules) {
  console.log(
    `  ${m.id} | ${m.tabName} | cards: ${String(m.cards.length)} | rule chars: ${String(m.rule.length)}`,
  )
}
console.log(`sample: ${sampleModule.id} | cards: ${String(sampleModule.cards.length)}`)
console.log(`module keys: ${Object.keys(modules[0]).join(", ")}`)
console.log(`card keys: ${Object.keys(modules[0].cards[0]).join(", ")}`)
console.log(`exercise: ${exercise.exerciseId}`)
console.log(
  `  paragraphs: ${String(exercise.paragraphs.length)} | questions: ${String(exercise.questions.length)} | flashcards: ${String(exercise.flashcards.length)}`,
)
